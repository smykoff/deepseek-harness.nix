#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

# Bump the packaged dsh version (and optionally the Node.js runtime).
#
#   bash scripts/update.sh                      # follow the npm `latest` tag
#   bash scripts/update.sh --node-version 24.x  # also repin the Node.js runtime

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing dependency: $1" >&2; exit 1; }; }
need curl
need jq
need nix
need npm

registry='https://registry.npmjs.org/@deepseek-ai%2Fdsh'
current=$(jq -r .version sources.json)
current_node=$(jq -r .node.version sources.json)

latest=$(curl -fsSL "$registry" | jq -r '."dist-tags".latest')
node_version=$current_node
if [ "${1:-}" = "--node-version" ]; then
  node_version=${2:?usage: $0 [--node-version <version>]}
fi

version_changed=false
node_changed=false
[ "$latest" != "$current" ] && version_changed=true
[ "$node_version" != "$current_node" ] && node_changed=true

if [ "$version_changed" = false ] && [ "$node_changed" = false ]; then
  echo "up to date: dsh $current, node $current_node"
  exit 0
fi

# --- Node.js runtime pins ---------------------------------------------------
if [ "$node_changed" = true ]; then
  echo "pinning Node.js $node_version"
  declare -A node_files=(
    [x86_64-linux]="node-v${node_version}-linux-x64.tar.xz"
    [aarch64-linux]="node-v${node_version}-linux-arm64.tar.xz"
    [x86_64-darwin]="node-v${node_version}-darwin-x64.tar.gz"
    [aarch64-darwin]="node-v${node_version}-darwin-arm64.tar.gz"
  )
  node_json=$(jq -n --arg v "$node_version" '{version: $v}')
  for sys in "${!node_files[@]}"; do
    url="https://nodejs.org/dist/v${node_version}/${node_files[$sys]}"
    hash=$(nix store prefetch-file --json "$url" | jq -r .hash)
    node_json=$(jq --arg s "$sys" --arg u "$url" --arg h "$hash" '.[$s] = {url: $u, hash: $h}' <<<"$node_json")
  done
  jq --argjson n "$node_json" '.node = $n' sources.json >sources.json.tmp
  mv sources.json.tmp sources.json
fi

# --- dsh version + dependency lockfile --------------------------------------
if [ "$version_changed" = true ]; then
  jq -n --arg v "$latest" '{
    name: "dsh-npm-deps",
    private: true,
    description: "Pinned dependency set for the dsh Nix package. Regenerated by scripts/update.sh.",
    dependencies: { "@deepseek-ai/dsh": $v },
  }' >npm/package.json

  ( cd npm && npm install --package-lock-only --ignore-scripts --no-audit --no-fund --loglevel=error )

  jq --arg v "$latest" '.version = $v' sources.json >sources.json.tmp
  mv sources.json.tmp sources.json

  # fetchNpmDeps only reports the hash of a lockfile it has not seen before, so
  # let the build fail once and read `got:` out of the mismatch error.
  set +e
  log=$(nix build .#default --no-link -L 2>&1)
  status=$?
  set -e
  new_hash=$(printf '%s\n' "$log" | sed -n 's/.*got:[[:space:]]*\(sha256-[A-Za-z0-9+/=]*\).*/\1/p' | head -n1)

  if [ -z "$new_hash" ]; then
    printf '%s\n' "$log" >&2
    echo "could not determine npmDepsHash (build exit status $status)" >&2
    exit 1
  fi

  jq --arg h "$new_hash" '.npmDepsHash = $h' sources.json >sources.json.tmp
  mv sources.json.tmp sources.json
fi

nix build .#default --no-link -L

if [ "$version_changed" = true ]; then
  echo "updated: dsh $current -> $latest"
  echo "version=$latest" >>"${GITHUB_OUTPUT:-/dev/null}"
else
  echo "updated: node $current_node -> $node_version"
fi
